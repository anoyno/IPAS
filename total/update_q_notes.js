files.forEach(file => {
  let content = fs.readFileSync(file, 'utf8');
  const match = content.match(/const questions = (\[[\s\S]*?\]);\n/);
  if (!match) { console.log(`Could not find questions in ${file}`); return; }

  let questions;
  try { questions = eval(match[1]); } catch(e) { console.error('Parse error:', e); return; }

  questions.forEach(q => {
    if (q.sourceKey !== 'subject1-official') return;
    const upd = updates[q.no];
    if (!upd) return;
    if (upd.notes) q.notes = upd.notes;
    if (upd.explanation) q.explanation = upd.explanation;
    if (upd.notes && q.notes.length === 1) q.notesSummary = '名詞白話解說';
  });

  const newQsString = JSON.stringify(questions, null, 2);
  content = content.replace(match[0], `const questions = ${newQsString};\n`);
  fs.writeFileSync(file, content, 'utf8');
  console.log(`Updated ${file}`);
});
